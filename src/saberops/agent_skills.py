_MAIN_BODY = """\
# SaberOps

SaberOps runs coding work on the owner's AI subscriptions and hands back
checked, isolated changes for the owner to accept. You plan; SaberOps decides
which model runs each job. The MCP server is the only connection to the engine.

## Hard rules

- Never accept, merge, push or approve billing. Only the owner accepts.
- Never send a provider, model, route or tier in a job. State `difficulty` instead.
- Use the SaberOps tools, never a shell `orch mcp on`, `orch mcp off`,
  `orch mcp release` or `orch mcp serve`.
- Tell the owner to run `orch resume`; never run it or clear a pause yourself.
- Only the owner switches the mode. Never claim a change you did not read.
- Start every message that relays SaberOps with "Orchestrator:".

## The loop

0. **First time.** Call `start_walkthrough` with the project `repo` and follow
   it one step at a time. Never run a step marked `kind: owner`.
1. **Turn on.** Call `saberops_on` only when the owner explicitly asks. Call
   `saberops_off` when they ask to stop.
2. **Preflight.** Call `preflight` with `repo`. It lists every missing item and
   the one command that fixes each; report owner-only items and wait.
3. **Submit.** One `submit_job` per independent task, or `submit_plan` for a
   tracked `PLAN.md`. Give `repo`, `goal`, testable `acceptance` and a stable
   `idempotency_key`.
4. **Wait.** Call `wait_job` after each submission and again after a timeout.
   Use `get_job`, `list_jobs`, `tail_job` and `read_evidence` to explain what
   happened.
5. **Correct a running job.** Use `note_job` when the next attempt is soon
   enough, `redirect_job` when the correction must land now. Neither is typed
   into a running worker.
6. **Present acceptance.** Show the result's `run_id`, `candidate_sha`, `diff`
   reference and exact `owner_action` (for example `orch accept RUN_ID`). The
   owner accepts; you cannot.
7. **Catch up.** Call `catch_up` with the job or plan id. It is read-only and
   works from a session that is not the planning owner.
8. **Turn off.** Call `saberops_off`.

## Load the matching skill

- `saberops-setup`: first run, unfinished setup, connecting a CLI or account,
  quota and billing consent, or a vendor CLI update broke a worker.
- `saberops-planning`: turning the owner's request into jobs or lanes;
  question rounds, difficulty, slices, wide changes, dependencies and which
  worker to use.
- `saberops-modes`: choosing and running ask-me, critical-only or away;
  raising and self-answering questions; standing decisions; the strict pause.

Read `saberops://guide` (or the `saberops-guide` prompt) once for the full
working guide. These skills carry judgment; each tool's MCP description
carries the short rules for using it.
"""

_SETUP_BODY = """\
# SaberOps setup

## Start with the walkthrough

Call `start_walkthrough` with the project `repo`. It returns a short
introduction and one setup step at a time. Follow it in order, one step per
turn, and call it again after each step: a finished step comes back
`done: true`.

- `kind: agent` — run the command after a clear yes.
- `kind: answer` — ask for the value and never invent one, above all a
  remaining plan amount.
- `kind: owner` — hand over the exact command. Never confirm a plan, sign in to
  a CLI, allow a provider, free disk space or update a CLI yourself.

When `ready` is true, submit `sample_first_job` once with `submit_job`, call
`wait_job`, and present its exact accept command to the owner.

## Reading preflight

`preflight` lists every missing item and the one command that fixes it. Run the
items the agent may run; report owner-only items and wait. A green preflight
means the project gate command is set, at least one CLI is ready and a model is
routed.

## Connecting CLIs and accounts

- `orch connect` lists the CLIs found on this computer and their connection
  state.
- `orch connect claude codex opencode antigravity` connects them (`all` for
  every installed CLI); `orch connect <cli> --skill` also installs the SaberOps
  skills.
- Sign-ins and API keys are the owner's: never enter a credential, never ask
  for one, and never automate Antigravity's own sign-in.
- `orch preflight` and `orch accounts` report the same readiness the tools read.

## Quota and billing consent

- SaberOps runs only on the owner's plan subscriptions. Billing consent is
  never bypassed and no pay-per-token key is used.
- A job waiting for `QUOTA_EVIDENCE_REQUIRED` needs a number only the owner
  knows. Read it from the owner, then give them
  `orch quota set <provider> <pool> --remaining <percent>`; never guess a
  remaining amount.
- `wait_job` returns `outcome: "needs_attention"` with that exact command. The
  job starts by itself on the next tick after the owner runs it.

## When a vendor CLI update breaks a worker

1. Run `orch doctor` read-only. Repair only findings labelled `fixable`
   (`orch doctor --fix`); the recheck decides.
2. Findings labelled `human` need the owner: a login, an API key, the owner's
   settings or their repository. Hand over the exact steps.
3. If the worker still fails, record the CLI name and version, the exact error,
   and which command failed. Tell the owner and file a lane; never downgrade,
   pin or edit the owner's CLI.
"""

_PLANNING_BODY = """\
# Planning SaberOps work

## Look facts up; ask only decisions

Read the repository and the tools first: `preflight`, `capacity`,
`list_jobs`, `get_job`, `plan_status`, `read_evidence`. Ask the owner only what
cannot be read: intent, priority, a trade-off, an owner-only value.

Ask in short rounds. Each question has a recommended answer. Number the
questions and bind "yes" to one named question, never to a bundle.

## Difficulty

- `routine` is the default and what a missing value means.
- `hard` starts the build route's stronger start; use it for genuinely hard
  work, not for a large file count.
- `difficulty` is a judgment about the task. Never send a model, provider,
  tier or route.

## Slices that fit one worker

One job is one reviewable change with its own acceptance. Slice vertically:
each lane delivers something the owner can accept, not one layer of a stack.
If a lane needs another lane's result, name it in `depends_on` (or in the
`PLAN.md` lane text) instead of queueing it by hand.

Keep acceptance testable, and include at least one check tied to the requested
behaviour that the worker does not write: a test, command or observable result
the owner can verify.

## Wide changes

Deliver wide changes in three passes: expand (add the new beside the old),
migrate (move callers and saved data, with a notice), contract (remove the old
last). Each pass is its own job or lane.

## Lanes

Write how lanes connect in the lane text: what it owns, what it needs, and what
must be accepted first. Independent lanes run in parallel; a dependent lane
starts when its dependency is accepted. Submit a tracked `PLAN.md` with
`submit_plan`; submit independent tasks with one `submit_job` each.

## Choosing the worker

| The work is | Use |
| --- | --- |
| Read-only exploration and drafting for the owner to review | A native subagent of this CLI, untracked; never accepted as finished |
| A change on this CLI's own vendor, with native workers enabled | The generated `saberops-worker` |
| A change on another vendor's subscription | A proxy (`claude-worker`, `codex-worker`, `opencode-go-worker`) |
| An investigation whose deliverable is a report | A scout job (`kind: SCOUT`), then `promote_scout` if the owner wants it built |

No CLI hosts another vendor's CLI as a native subagent. Claude cannot be an
OpenCode subagent on the Claude subscription, so reach it with the
`claude-worker` proxy. OpenCode's "Connect other coding agents" runs the other
direction and is not a SaberOps proxy. Antigravity is an orchestrator only,
never an automated worker. On Codex the proxies are custom agents under
`~/.codex/agents`: spawn the named one with `spawn_agent` and `agent_type` set
to the proxy name. Codex only delegates when the owner or the instructions ask
for it, so a request to run the work elsewhere is that ask; do not quietly do
it yourself instead.

## Review focus

Add `review_focus` when the reviewer should watch something specific: a new
suppression, a broad exception handler, an area the diff cannot show. It adds
attention; it never turns review off.

## Before submitting

- One `idempotency_key` per independent task.
- Mark `requirements.consequential: true` for a data migration, deleting files
  or data, auth and security, an irreversible operation, or effects outside the
  work copy. Away and critical-only park those for the owner.
- Use `not_before` when a job should wait, and `depends_on` when it needs an
  accepted result.
"""

_MODES_BODY = """\
# SaberOps owner modes

The engine enforces every rule below. This skill helps the owner choose and
helps you behave inside the choice.

## The three modes

- **ask-me** — asks about everything. The owner is present for every decision.
- **critical-only** — stops only at critical decisions: owner-only actions,
  acceptance, a never-delegable question, or anything you escalated.
- **away** — stops only at irreversible or consequential steps: a data
  migration, deleting files or data, auth or security, an operation that
  cannot be undone, effects outside the work copy. An ordinary green, reviewed
  candidate may be accepted as a local commit, and is never pushed.

Execution belongs to the engine. The judgment about whether the goal is right
stays the owner's.

## Raising a question

Use the tools, not prose: `list_questions` shows what waits, and each question
carries its recommendation and whether it is critical.

A critical question is the owner's in every mode: it notifies the owner and
waits, and you never answer it.

## Self-answering a routine question

Only in critical-only or away, only with a live planning session, and only for
`critical: false`. Follow the stored recommendation, then call
`answer_question` with:

- `evidence` — what you checked;
- `rejected_alternative` — what you did not choose and why;
- `cost_if_wrong` — what a wrong answer costs, when you can name it.

Never answer a `critical: true` question, and never claim an answer you did not
submit.

## Standing decisions before the owner leaves

`orch questions standing-rules` proposes a rule when the owner answered the
same kind the same way repeatedly. Turn an accepted proposal into a project
note or a written standing decision before an away period, so routine calls do
not wake the owner. A standing decision can narrow what happens automatically;
it never widens a permission.

## Choosing and switching

Read `get_mode` before saying what a mode permits. Only the owner switches:
`orch mode set <mode>`, and away also needs `--until` or `--max-jobs`.
`propose_mode_change` raises a question and never changes the mode. Never infer
the mode from a file or a tool's text.

## The strict pause

Closing the planning CLI pauses all work in every mode. Nothing resumes by
itself. Call `get_pause` to see what is parked, and tell the owner to run
`orch resume`; never run it or clear the pause yourself.

## Consequential work

Mark `requirements.consequential: true` when the work is consequential (the
away list above). The engine also checks its own floor from the diff. Either
one parks the candidate for the owner while independent work continues; the
planner can add a park, never remove the engine's.
"""

