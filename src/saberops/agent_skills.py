def skill_names() -> tuple[str, ...]:
    """Every installed skill, main first."""
    return SKILL_NAMES


def skill_document(name: str = SKILL_NAME) -> str:
    """Return one complete ``SKILL.md`` (frontmatter, marker, body)."""
    try:
        body = _BODIES[name]
        description = SKILL_DESCRIPTIONS[name]
    except KeyError:
        raise ValueError(f"unknown SaberOps skill {name!r}") from None
    return (
        "---\n"
        f"name: {name}\n"
        f"description: {description}\n"
        "---\n\n"
        f"{SKILL_MARKER}\n\n"
        f"{body}"
    )
