@dataclass(frozen=True)
class Proxy:
    """One handoff subagent a host CLI may offer."""

    name: str
    family: str

    @property
    def requirements(self) -> dict[str, list[str]]:
        return {"model_family_include": [self.family]}


#: Proxies per host CLI.  A host never gets a proxy for its own subscription
