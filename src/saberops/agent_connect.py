"""Connect SaberOps to coding-agent CLIs as an MCP server (``orch connect``).

Every supported agent gets the same stdio server, ``<orch> mcp serve``, with
``SABEROPS_PROFILE`` passed through when a profile is active. Where the agent
ships its own registration command it is used (Claude Code, Codex,
Antigravity), so its config stays in the format it owns. Agents configured by
a JSON file (OpenCode, Cursor) are edited only when the file is plain JSON,
after a timestamped backup; a file with comments is never rewritten, the
snippet is returned for the owner to paste instead.

Nothing here talks to a model or a network. Command execution and the home
directory are injectable so tests never touch the owner's real agents.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field, replace
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

__all__ = [
    "AGENTS",
    "SKILL_DESCRIPTION",
    "SKILL_MARKER",
    "SKILL_NAME",
    "Agent",
    "ConnectResult",
    "agent_by_slug",
    "agent_rows",
    "connect",
    "disconnect",
    "install_skill",
    "is_connected",
    "orch_command",
    "remove_skill",
    "server_snippet",
    "skill_document",
    "skill_path",
]

SERVER_NAME = "saberops"

#: Directory name of the SaberOps skill inside each agent's skill root.
SKILL_NAME = "saberops"

#: Ownership marker.  A file without it was not written by SaberOps and is
#: never overwritten or deleted.
SKILL_MARKER = (
    "<!-- saberops-managed-skill v1: generated by `orch connect`; edits are overwritten -->"
)

#: Frontmatter description.  Front-loaded trigger words so each CLI's skill
#: matcher offers it when the owner says "turn on saberops".
SKILL_DESCRIPTION = (
    "Turn SaberOps on and hand coding work to it over MCP. Use when the user says "
    '"turn on saberops", asks to start or use SaberOps, or asks about SaberOps jobs, '
    "results, waits or acceptance."
)

Runner = Callable[[Sequence[str], Path | None], "subprocess.CompletedProcess[str]"]


def _run(argv: Sequence[str], cwd: Path | None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        list(argv), cwd=cwd, capture_output=True, text=True, timeout=60, check=False
    )


@dataclass(frozen=True)
class Agent:
    slug: str
    name: str
    executable: str
    method: str  # "cli" (own mcp add/remove) or "json" (config file)
    project_scope: bool = False
    config_files: tuple[str, ...] = field(default_factory=tuple)  # json agents, user scope
    project_file: str = ""
    #: User-scope skill root, relative to the home directory.  Empty means the
    #: agent has no local skill format (``orch connect --skill`` reports it as
    #: unsupported).
    skill_dir: str = ""


# Skill locations, each verified against the agent's own documentation or its
# installed help/binary on 2026-11-19:
#   Claude Code  ~/.claude/skills/<name>/SKILL.md
#   Codex        $CODEX_HOME/skills/<name>/SKILL.md  (skill-installer target)
#   OpenCode     ~/.config/opencode/skills/<name>/SKILL.md
#   Antigravity  ~/.gemini/config/skills/<name>/SKILL.md
AGENTS: tuple[Agent, ...] = (
    Agent("claude", "Claude Code", "claude", "cli", project_scope=True, skill_dir=".claude/skills"),
    Agent("codex", "Codex", "codex", "cli", skill_dir=".codex/skills"),
    Agent(
        "antigravity",
        "Antigravity",
        "agy",
        "cli",
        skill_dir=".gemini/config/skills",
    ),
    Agent(
        "opencode",
        "OpenCode",
        "opencode",
        "json",
        project_scope=True,
        config_files=(".config/opencode/opencode.json", ".config/opencode/opencode.jsonc"),
        project_file="opencode.json",
        skill_dir=".config/opencode/skills",
    ),
    Agent(
        "cursor",
        "Cursor",
        "cursor",
        "json",
        project_scope=True,
        config_files=(".cursor/mcp.json",),
        project_file=".cursor/mcp.json",
    ),
)


def agent_by_slug(slug: str) -> Agent | None:
    return next((agent for agent in AGENTS if agent.slug == slug.strip().lower()), None)


@dataclass(frozen=True)
class ConnectResult:
    agent: str
    ok: bool
    message: str
    commands: tuple[str, ...] = ()
    snippet: str = ""
    #: Absolute path of the skill file this result is about, when relevant.
    skill_path: str = ""
    #: The exact file content for a dry run (empty otherwise).
    skill_content: str = ""
    #: installed | would-install | unchanged | refused | removed | absent | unsupported
    skill_action: str = ""


def orch_command() -> str:
    """Absolute path of the currently running ``orch`` launcher."""
    venv_orch = Path(sys.executable).parent / "orch"
    if venv_orch.is_file():
        return str(venv_orch.resolve())
    if sys.argv and sys.argv[0]:
        argv_path = Path(sys.argv[0])
        if argv_path.name == "orch" and argv_path.is_file():
            return str(argv_path.resolve())
    found = shutil.which("orch")
    return str(Path(found).resolve()) if found else "orch"


def conflicting_orch_on_path() -> str | None:
    """Return another ``orch`` path on PATH when it differs from the running one."""
    found = shutil.which("orch")
    if not found:
        return None
    resolved_found = str(Path(found).resolve())
    running = orch_command()
    if running != "orch" and resolved_found != running:
        return resolved_found
    return None


def _with_path_warning(message: str) -> str:
    other = conflicting_orch_on_path()
    if not other:
        return message
    return (
        f"{message} Warning: another 'orch' exists on PATH at {other}; "
        f"registering running {orch_command()}."
    )


def _env() -> dict[str, str]:
    profile = os.environ.get("SABEROPS_PROFILE", "").strip()
    return {"SABEROPS_PROFILE": profile} if profile else {}


def _home(home: Path | None) -> Path:
    return home if home is not None else Path.home()


def server_snippet(agent: Agent) -> str:
    """The exact config an owner can paste by hand."""
    orch = orch_command()
    env = _env()
    if agent.slug == "opencode":
        entry: dict[str, Any] = {
            "type": "local",
            "command": [orch, "mcp", "serve"],
            "enabled": True,
        }
        if env:
            entry["environment"] = env
        return json.dumps({"mcp": {SERVER_NAME: entry}}, indent=2)
    if agent.slug == "codex":
        lines = [f"[mcp_servers.{SERVER_NAME}]", f'command = "{orch}"', 'args = ["mcp", "serve"]']
        if env:
            lines += [f"[mcp_servers.{SERVER_NAME}.env]"] + [f'{k} = "{v}"' for k, v in env.items()]
        return "\n".join(lines)
    server: dict[str, Any] = {"command": orch, "args": ["mcp", "serve"]}
    if env:
        server["env"] = env
    return json.dumps({"mcpServers": {SERVER_NAME: server}}, indent=2)


def skill_path(agent: Agent, *, home: Path | None = None) -> Path | None:
    """Absolute ``SKILL.md`` path for one agent, or ``None`` when unsupported."""
    if not agent.skill_dir:
        return None
    return _home(home) / agent.skill_dir / SKILL_NAME / "SKILL.md"


def skill_document() -> str:
    """The instruction file content, generated from the live MCP guide.

    The loop section names the tools the MCP server exposes and the result
    fields it returns; the full guide is appended from
    :data:`saberops.mcp.guide.GUIDE` so the two cannot drift apart.
    """
    from saberops.mcp.guide import GUIDE

    return (
        "---\n"
        f"name: {SKILL_NAME}\n"
        f"description: {SKILL_DESCRIPTION}\n"
        "---\n\n"
        f"{SKILL_MARKER}\n\n"
        "# SaberOps\n\n"
        "This skill was installed by `orch connect`. The SaberOps MCP server is the\n"
        "only connection to the engine; this file only teaches the loop.\n\n"
        "## The loop\n\n"
        "1. **Turn on.** When the owner explicitly asks to turn SaberOps on, call\n"
        "   `saberops_on`. Never call it on your own initiative.\n"
        "2. **Preflight.** Call `preflight` with the project `repo` before submitting\n"
        "   work. It lists every missing item and the one command that fixes each;\n"
        "   report owner-only items (billing, sign-in, routes, check command) and wait.\n"
        "3. **Submit one job per independent task.** Call `submit_job` once per task\n"
        "   with `repo`, `goal`, testable `acceptance`, and a stable\n"
        "   `idempotency_key`. Never send a provider, model or route.\n"
        "4. **Wait.** Call `wait_job` after each submission. It returns on a final\n"
        "   outcome, a blocking question, or the timeout; call it again after a\n"
        "   timeout. Use `get_job`, `list_jobs` and `read_evidence` to explain what\n"
        "   happened. If the owner corrects a running job, call `note_job`: the note\n"
        "   is stored and reaches the worker once at its next attempt, never mid-tool.\n"
        "5. **Present the owner acceptance action.** When a job succeeds, show the\n"
        "   result's `run_id`, `candidate_sha`, `diff` reference and exact\n"
        "   `owner_action` (for example `orch accept RUN_ID`). The owner accepts;\n"
        "   you cannot accept, merge, push or approve billing.\n"
        "6. **Catch up.** When the owner asks to \"catch me up\" about a job, call\n"
        "   `catch_up` with its `job_id`. It is read-only, works from a session that\n"
        "   is not the planning owner, and returns the original request, candidate,\n"
        "   latest check and review, any open question and the next allowed action.\n"
        "7. **Turn off.** Call `saberops_off` when the owner asks to stop.\n\n"
        "## Full guide\n\n" + GUIDE
    )


def install_skill(
    slug: str, *, home: Path | None = None, dry_run: bool = False
) -> ConnectResult:
    """Install the SaberOps instruction skill for one agent.

    Refuses to overwrite (or later delete) a file without :data:`SKILL_MARKER`,
    so a skill the owner wrote by hand is never touched.  A dry run returns the
    exact path and content and writes nothing.
    """
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    path = skill_path(agent, home=home)
    if path is None:
        return ConnectResult(
            slug,
            True,
            f"{agent.name} has no local skill format; the SaberOps skill is unsupported there.",
            skill_action="unsupported",
        )
    content = skill_document()
    if dry_run:
        return ConnectResult(
            slug,
            True,
            f"Would write the SaberOps skill to {path}.",
            skill_path=str(path),
            skill_content=content,
            skill_action="would-install",
        )
    if path.exists():
        if not path.is_file():
            return ConnectResult(
                slug,
                False,
                f"{path} is not a regular file; left untouched.",
                skill_path=str(path),
                skill_action="refused",
            )
        existing = path.read_text(encoding="utf-8", errors="replace")
        if SKILL_MARKER not in existing:
            return ConnectResult(
                slug,
                False,
                f"{path} exists and was not written by SaberOps; left untouched.",
                skill_path=str(path),
                skill_action="refused",
            )
        if existing == content:
            return ConnectResult(
                slug,
                True,
                f"SaberOps skill already up to date at {path}.",
                skill_path=str(path),
                skill_action="unchanged",
            )
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(content, encoding="utf-8")
        tmp.replace(path)
    except OSError as exc:
        return ConnectResult(
            slug,
            False,
            f"Could not write the SaberOps skill to {path}: {exc}",
            skill_path=str(path),
            skill_action="refused",
        )
    return ConnectResult(
        slug,
        True,
        f"Installed the SaberOps skill at {path}.",
        skill_path=str(path),
        skill_action="installed",
    )


def remove_skill(slug: str, *, home: Path | None = None) -> ConnectResult:
    """Remove only the skill file SaberOps wrote, and its now-empty folder."""
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    path = skill_path(agent, home=home)
    if path is None:
        return ConnectResult(
            slug,
            True,
            f"{agent.name} has no local skill format; there is no SaberOps skill to remove.",
            skill_action="unsupported",
        )
    if not path.exists():
        return ConnectResult(
            slug,
            True,
            f"No SaberOps skill is installed for {agent.name}.",
            skill_path=str(path),
            skill_action="absent",
        )
    if not path.is_file():
        return ConnectResult(
            slug,
            False,
            f"{path} is not a regular file; left untouched.",
            skill_path=str(path),
            skill_action="refused",
        )
    existing = path.read_text(encoding="utf-8", errors="replace")
    if SKILL_MARKER not in existing:
        return ConnectResult(
            slug,
            False,
            f"{path} was not written by SaberOps; left untouched.",
            skill_path=str(path),
            skill_action="refused",
        )
    path.unlink()
    try:
        path.parent.rmdir()
    except OSError:
        pass  # another file lives there; leave it in place
    return ConnectResult(
        slug,
        True,
        f"Removed the SaberOps skill at {path}.",
        skill_path=str(path),
        skill_action="removed",
    )


def _cli_add(agent: Agent, project: bool) -> list[str]:
    orch = orch_command()
    env = _env()
    if agent.slug == "claude":
        argv = ["claude", "mcp", "add", "--scope", "project" if project else "user", SERVER_NAME]
        for key, value in env.items():
            argv += ["-e", f"{key}={value}"]
        return [*argv, "--", orch, "mcp", "serve"]
    if agent.slug == "codex":
        argv = ["codex", "mcp", "add", SERVER_NAME]
        for key, value in env.items():
            argv += ["--env", f"{key}={value}"]
        return [*argv, "--", orch, "mcp", "serve"]
    argv = ["agy", "mcp", "add"]
    for key, value in env.items():
        argv += ["-e", f"{key}={value}"]
    return [*argv, SERVER_NAME, orch, "mcp", "serve"]


def _cli_remove(agent: Agent, project: bool) -> list[str]:
    if agent.slug == "claude":
        return ["claude", "mcp", "remove", "--scope", "project" if project else "user", SERVER_NAME]
    return [agent.executable, "mcp", "remove", SERVER_NAME]


def _json_path(agent: Agent, *, project: Path | None, home: Path | None) -> Path:
    if project is not None:
        return project / agent.project_file
    base = _home(home)
    for name in agent.config_files:
        if (base / name).is_file():
            return base / name
    return base / agent.config_files[0]


def _json_edit(path: Path, agent: Agent, *, remove: bool) -> ConnectResult:
    data: dict[str, Any] = {}
    if path.is_file():
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            return ConnectResult(
                agent.slug,
                False,
                f"{path} has comments or is not plain JSON, so it was left untouched. "
                "Paste the snippet into it by hand.",
                snippet=server_snippet(agent),
            )
        if not isinstance(loaded, dict):
            return ConnectResult(agent.slug, False, f"{path} is not a JSON object; left untouched.")
        data = loaded
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        backup = path.with_name(f"{path.name}.bak-saberops-{stamp}")
        backup.write_bytes(path.read_bytes())
    key = "mcp" if agent.slug == "opencode" else "mcpServers"
    servers = data.get(key) if isinstance(data.get(key), dict) else {}
    assert isinstance(servers, dict)
    if remove:
        if SERVER_NAME not in servers:
            return ConnectResult(agent.slug, True, f"{agent.name} was not connected.")
        servers.pop(SERVER_NAME)
    else:
        servers[SERVER_NAME] = json.loads(server_snippet(agent))[key][SERVER_NAME]
    data[key] = servers
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)
    verb = "Disconnected" if remove else "Connected"
    return ConnectResult(agent.slug, True, f"{verb} {agent.name} ({path}).")


def _with_skill(
    result: ConnectResult,
    agent: Agent,
    *,
    home: Path | None,
    dry_run: bool,
) -> ConnectResult:
    """Attach the instruction-file step to an MCP registration result."""
    if not result.ok:
        return result
    skill = install_skill(agent.slug, home=home, dry_run=dry_run)
    return replace(
        result,
        ok=result.ok and skill.ok,
        message=f"{result.message} {skill.message}".strip(),
        skill_path=skill.skill_path,
        skill_content=skill.skill_content,
        skill_action=skill.skill_action,
    )


def connect(
    slug: str,
    *,
    project: Path | None = None,
    dry_run: bool = False,
    runner: Runner | None = None,
    home: Path | None = None,
    skill: bool = False,
) -> ConnectResult:
    """Register SaberOps with one agent (user scope, or ``project`` folder).

    With ``skill=True`` also install the small instruction file that teaches
    the submit/wait/accept loop, where the agent supports a local skill.
    """
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    if project is not None and not agent.project_scope:
        return ConnectResult(slug, False, f"{agent.name} has no per-project MCP setting.")
    if agent.method == "json":
        path = _json_path(agent, project=project, home=home)
        if dry_run:
            preview = ConnectResult(
                slug,
                True,
                _with_path_warning(f"Would add SaberOps to {path}."),
                snippet=server_snippet(agent),
            )
            return _with_skill(preview, agent, home=home, dry_run=True) if skill else preview
        edited = _json_edit(path, agent, remove=False)
        json_result = ConnectResult(
            edited.agent,
            edited.ok,
            _with_path_warning(edited.message),
            edited.commands,
            edited.snippet,
        )
        return _with_skill(json_result, agent, home=home, dry_run=False) if skill else json_result
    if shutil.which(agent.executable) is None and runner is None:
        return ConnectResult(
            slug, False, f"{agent.name} is not installed.", snippet=server_snippet(agent)
        )
    run = runner or _run
    commands = []
    if not dry_run:
        # Re-adding replaces a stale entry (an old orch path or profile).
        run(_cli_remove(agent, project is not None), project)
    argv = _cli_add(agent, project is not None)
    commands.append(" ".join(argv))
    if dry_run:
        preview = ConnectResult(
            slug, True, _with_path_warning("Would run:"), commands=tuple(commands)
        )
        return _with_skill(preview, agent, home=home, dry_run=True) if skill else preview
    result = run(argv, project)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip().splitlines()
        return ConnectResult(
            slug,
            False,
            f"{agent.name} refused: {detail[-1] if detail else 'exit ' + str(result.returncode)}",
            commands=tuple(commands),
            snippet=server_snippet(agent),
        )
    connected = ConnectResult(
        slug, True, _with_path_warning(f"Connected {agent.name}."), commands=tuple(commands)
    )
    return _with_skill(connected, agent, home=home, dry_run=False) if skill else connected


def disconnect(
    slug: str,
    *,
    project: Path | None = None,
    runner: Runner | None = None,
    home: Path | None = None,
    skill: bool = True,
) -> ConnectResult:
    """Disconnect one agent; also remove the SaberOps skill it owns."""
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    if agent.method == "json":
        res = _json_edit(_json_path(agent, project=project, home=home), agent, remove=True)
    elif shutil.which(agent.executable) is None and runner is None:
        # Still remove the skill file: an uninstalled CLI may leave one behind.
        res = ConnectResult(slug, True, f"{agent.name} is not installed; nothing to disconnect.")
    else:
        argv = _cli_remove(agent, project is not None)
        result = (runner or _run)(argv, project)
        if result.returncode != 0:
            res = ConnectResult(
                slug, True, f"{agent.name} was not connected.", commands=(" ".join(argv),)
            )
        else:
            res = ConnectResult(
                slug, True, f"Disconnected {agent.name}.", commands=(" ".join(argv),)
            )
    if not skill:
        return res
    skill_result = remove_skill(slug, home=home)
    return replace(
        res,
        ok=res.ok and skill_result.ok,
        message=f"{res.message} {skill_result.message}".strip(),
        skill_path=skill_result.skill_path,
        skill_action=skill_result.skill_action,
    )


def is_connected(agent: Agent, *, home: Path | None = None, runner: Runner | None = None) -> bool:
    """Cheap user-scope check: read the agent's own registry, never start it."""
    base = _home(home)
    try:
        if agent.slug == "claude":
            data = json.loads((base / ".claude.json").read_text(encoding="utf-8"))
            return SERVER_NAME in (data.get("mcpServers") or {})
        if agent.slug == "codex":
            text = (base / ".codex" / "config.toml").read_text(encoding="utf-8")
            return re.search(rf"^\[mcp_servers\.{SERVER_NAME}\]", text, re.M) is not None
        if agent.slug == "antigravity":
            # Its registry format is private; its own list command is fast (~0.1 s).
            if runner is None and (
                shutil.which(agent.executable) is None
                or os.environ.get("PYTEST_CURRENT_TEST") is not None
            ):
                return False
            listed = (runner or _run)([agent.executable, "mcp", "list"], None)
            return (
                listed.returncode == 0
                and re.search(rf"\b{SERVER_NAME}\b", listed.stdout or "") is not None
            )
        path = _json_path(agent, project=None, home=home)
        data = json.loads(path.read_text(encoding="utf-8"))
        key = "mcp" if agent.slug == "opencode" else "mcpServers"
        return SERVER_NAME in (data.get(key) or {})
    except (OSError, ValueError, AttributeError):
        return False


def agent_rows(*, home: Path | None = None) -> list[dict[str, Any]]:
    """Every supported agent: installed, connected, and a paste-able snippet."""
    rows = []
    for agent in AGENTS:
        rows.append(
            {
                "slug": agent.slug,
                "name": agent.name,
                "installed": shutil.which(agent.executable) is not None,
                "connected": is_connected(agent, home=home),
                "snippet": server_snippet(agent),
            }
        )
    return rows
