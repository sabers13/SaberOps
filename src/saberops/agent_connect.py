def orch_command() -> str:
    """Absolute path of the currently running ``orch`` launcher."""
    venv_orch = Path(sys.executable).parent / "orch"
    if venv_orch.is_file():
        return str(venv_orch.resolve())
    if sys.argv and sys.argv[0]:
        argv_path = Path(sys.argv[0])
        if argv_path.name == "orch" and argv_path.is_file():
            return str(argv_path.resolve())
    found = shutil.which("orch")
    return str(Path(found).resolve()) if found else "orch"


def conflicting_orch_on_path() -> str | None:
    """Return another ``orch`` path on PATH when it differs from the running one."""
    found = shutil.which("orch")
    if not found:
        return None
    resolved_found = str(Path(found).resolve())
    running = orch_command()
    if running != "orch" and resolved_found != running:
        return resolved_found
    return None


def _with_path_warning(message: str) -> str:
    other = conflicting_orch_on_path()
    if not other:
        return message
    return (
        f"{message} Warning: another 'orch' exists on PATH at {other}; "
        f"registering running {orch_command()}."
    )


def _env() -> dict[str, str]:
    profile = os.environ.get("SABEROPS_PROFILE", "").strip()
    return {"SABEROPS_PROFILE": profile} if profile else {}


def _home(home: Path | None) -> Path:
    return home if home is not None else Path.home()


def server_snippet(agent: Agent) -> str:
    """The exact config an owner can paste by hand."""
    orch = orch_command()
    env = _env()
    if agent.slug == "opencode":
        entry: dict[str, Any] = {
            "type": "local",
            "command": [orch, "mcp", "serve"],
            "enabled": True,
        }
        if env:
            entry["environment"] = env
        return json.dumps({"mcp": {SERVER_NAME: entry}}, indent=2)
    if agent.slug == "codex":
        lines = [f"[mcp_servers.{SERVER_NAME}]", f'command = "{orch}"', 'args = ["mcp", "serve"]']
        if env:
            lines += [f"[mcp_servers.{SERVER_NAME}.env]"] + [f'{k} = "{v}"' for k, v in env.items()]
        return "\n".join(lines)
    server: dict[str, Any] = {"command": orch, "args": ["mcp", "serve"]}
    if env:
        server["env"] = env
    return json.dumps({"mcpServers": {SERVER_NAME: server}}, indent=2)


def skill_path(agent: Agent, *, home: Path | None = None) -> Path | None:
    """Absolute ``SKILL.md`` path for one agent, or ``None`` when unsupported."""
    if not agent.skill_dir:
        return None
    return _home(home) / agent.skill_dir / SKILL_NAME / "SKILL.md"


