def install_agents(slug: str, *, home: Path | None = None, dry_run: bool = False) -> ConnectResult:
    """Install every proxy definition this host CLI supports.

    Each definition carries :data:`AGENT_MARKER`, is written atomically, and a
    file SaberOps did not write is never overwritten.  A dry run returns the
    exact path and content and writes nothing.
    """
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    proxies = PROXIES.get(agent.slug, ())
    if not proxies or not agent.agent_dir:
        return ConnectResult(
            slug,
            True,
            f"{agent.name} has no known subagent format; proxy definitions are unsupported there.",
            agent_action="unsupported",
        )
    files: list[AgentFile] = []
    missing_dir = False
    for proxy in proxies:
        path = agent_file_path(agent, proxy.name, home=home)
        assert path is not None
        missing_dir = missing_dir or not path.parent.exists()
        content = agent_document(agent.slug, proxy.name)
        files.append(_write_agent_file(agent, proxy, path, content, dry_run=dry_run))
    ok = all(item.ok for item in files)
    if not ok:
        action = "refused"
    elif dry_run:
        action = "would-install"
    elif all(item.action == "unchanged" for item in files):
        action = "unchanged"
    else:
        action = "installed"
    message = " ".join(item.message for item in files)
    if agent.slug == "claude" and missing_dir and action in {"installed", "would-install"}:
        message += (
            " Restart Claude Code once: it only watches ~/.claude/agents after that"
            " folder exists."
        )
    if agent.slug == "codex" and action in {"installed", "would-install"}:
        message += (
            " Codex lists each proxy by name as a custom agent; install the skill"
            " (`orch connect codex --skill`) so the planner is told to spawn it."
        )
    return ConnectResult(
        slug,
        ok,
        message,
        agent_files=tuple(files),
        agent_action=action,
    )


def remove_agents(slug: str, *, home: Path | None = None) -> ConnectResult:
    """Remove only marked proxy definitions, keeping foreign siblings."""
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    proxies = PROXIES.get(agent.slug, ())
    if not proxies or not agent.agent_dir:
        return ConnectResult(
            slug,
            True,
            f"{agent.name} has no known subagent format; there is nothing to remove.",
            agent_action="unsupported",
        )
    files: list[AgentFile] = []
    for proxy in proxies:
        path = agent_file_path(agent, proxy.name, home=home)
        assert path is not None
        if not path.exists():
            files.append(
                AgentFile(
                    proxy.name,
                    str(path),
                    action="absent",
                    message=f"No SaberOps proxy {proxy.name!r} is installed for {agent.name}.",
                )
            )
            continue
        if not path.is_file():
            files.append(
                AgentFile(
                    proxy.name,
                    str(path),
                    action="refused",
                    message=f"{path} is not a regular file; left untouched.",
                    ok=False,
                )
            )
            continue
        existing = path.read_text(encoding="utf-8", errors="replace")
        if AGENT_MARKER not in existing and AGENT_MARKER_TOML not in existing:
            files.append(
                AgentFile(
                    proxy.name,
                    str(path),
                    action="refused",
                    message=f"{path} was not written by SaberOps; left untouched.",
                    ok=False,
                )
            )
            continue
        path.unlink()
        files.append(
            AgentFile(
                proxy.name,
                str(path),
                action="removed",
                message=f"Removed the SaberOps proxy {proxy.name!r} at {path}.",
            )
        )
    ok = all(item.ok for item in files)
    if not ok:
        action = "refused"
    elif all(item.action == "absent" for item in files):
        action = "absent"
    else:
        action = "removed"
    if action == "removed":
        directory = agent_file_path(agent, proxies[0].name, home=home)
        assert directory is not None
        try:
            directory.parent.rmdir()
        except OSError:
            pass  # another file lives there; leave it in place
    return ConnectResult(
        slug,
        ok,
        " ".join(item.message for item in files),
        agent_files=tuple(files),
        agent_action=action,
    )


def _skill_rollup(files: Sequence[SkillFile], *, dry_run: bool = False) -> str:
    """One installed/removed state for a group of skill files."""
    if any(not item.ok for item in files):
        return "refused"
    actions = {item.action for item in files}
    if actions == {"unsupported"}:
        return "unsupported"
    if dry_run:
        return "would-install"
    if actions == {"unchanged"}:
        return "unchanged"
    if actions == {"absent"}:
        return "absent"
    if actions <= {"removed", "absent"}:
        return "removed"
    return "installed"


def _install_one_skill(
    agent: Agent, name: str, *, home: Path | None = None, dry_run: bool = False
) -> SkillFile:
    """Install one instruction skill for one agent.

    Refuses to overwrite (or later delete) a file without :data:`SKILL_MARKER`,
    so a skill the owner wrote by hand is never touched.  A dry run returns the
    exact path and content and writes nothing.
    """
    path = skill_path(agent, home=home, name=name)
    assert path is not None
    label = "SaberOps" if name == SKILL_NAME else name
    content = skill_document(name)
    if dry_run:
        return SkillFile(
            name,
            str(path),
            content,
            action="would-install",
            message=f"Would write the {label} skill to {path}.",
        )
    if path.exists():
        if not path.is_file():
            return SkillFile(
                name,
                str(path),
                action="refused",
                message=f"{path} is not a regular file; left untouched.",
                ok=False,
            )
        existing = path.read_text(encoding="utf-8", errors="replace")
        if SKILL_MARKER not in existing:
            return SkillFile(
                name,
                str(path),
                action="refused",
                message=f"{path} exists and was not written by SaberOps; left untouched.",
                ok=False,
            )
        if existing == content:
            return SkillFile(
                name,
                str(path),
                action="unchanged",
                message=f"The {label} skill is already up to date at {path}.",
            )
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(content, encoding="utf-8")
        tmp.replace(path)
    except OSError as exc:
        return SkillFile(
            name,
            str(path),
            action="refused",
            message=f"Could not write the {label} skill to {path}: {exc}",
            ok=False,
        )
    return SkillFile(
        name,
        str(path),
        action="installed",
        message=f"Installed the {label} skill at {path}.",
    )


def _remove_one_skill(agent: Agent, name: str, *, home: Path | None = None) -> SkillFile:
    """Remove only the skill file SaberOps wrote, and its now-empty folder."""
    path = skill_path(agent, home=home, name=name)
    assert path is not None
    label = "SaberOps" if name == SKILL_NAME else name
    if not path.exists():
        return SkillFile(
            name,
            str(path),
            action="absent",
            message=f"No {label} skill is installed for {agent.name}.",
        )
    if not path.is_file():
        return SkillFile(
            name,
            str(path),
            action="refused",
            message=f"{path} is not a regular file; left untouched.",
            ok=False,
        )
    existing = path.read_text(encoding="utf-8", errors="replace")
    if SKILL_MARKER not in existing:
        return SkillFile(
            name,
            str(path),
            action="refused",
            message=f"{path} was not written by SaberOps; left untouched.",
            ok=False,
        )
    path.unlink()
    try:
        path.parent.rmdir()
    except OSError:
        pass  # another file lives there; leave it in place
    return SkillFile(
        name,
        str(path),
        action="removed",
        message=f"Removed the {label} skill at {path}.",
    )


def _skill_result(
    slug: str, files: Sequence[SkillFile], *, action: str, dry_run: bool
) -> ConnectResult:
    main = next(item for item in files if item.name == SKILL_NAME)
    return ConnectResult(
        slug,
        all(item.ok for item in files),
        " ".join(item.message for item in files if item.message).strip(),
        skill_path=main.path,
        skill_content=main.content if dry_run else "",
        skill_action=action,
        skill_files=tuple(files),
    )


def install_skill(
    slug: str, *, home: Path | None = None, dry_run: bool = False
) -> ConnectResult:
    """Install the four SaberOps skills plus the native worker definition (F16).

    Every file carries an ownership marker, so a file SaberOps did not write
    is never overwritten or later removed.
    """
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    if not agent.skill_dir:
        return ConnectResult(
            slug,
            True,
            f"{agent.name} has no local skill format; the SaberOps skills are unsupported there.",
            skill_action="unsupported",
            skill_files=(SkillFile(SKILL_NAME, action="unsupported"),),
        )
    skill_files = tuple(
        _install_one_skill(agent, name, home=home, dry_run=dry_run) for name in SKILL_NAMES
    )
    skill = _skill_result(
        slug,
        skill_files,
        action=_skill_rollup(skill_files, dry_run=dry_run),
        dry_run=dry_run,
    )
    worker = install_worker(slug, home=home, dry_run=dry_run)
    files = tuple(skill.agent_files) + tuple(worker.agent_files)
    return replace(
        skill,
        ok=skill.ok and worker.ok,
        message=f"{skill.message} {worker.message}".strip(),
        agent_files=files,
        agent_action=worker.agent_action or skill.agent_action,
    )


def remove_skill(slug: str, *, home: Path | None = None) -> ConnectResult:
    """Remove every SaberOps skill and the native worker definition it owns."""
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    if not agent.skill_dir:
        return ConnectResult(
            slug,
            True,
            f"{agent.name} has no local skill format; there is no SaberOps skill to remove.",
            skill_action="unsupported",
            skill_files=(SkillFile(SKILL_NAME, action="unsupported"),),
        )
    skill_files = tuple(_remove_one_skill(agent, name, home=home) for name in SKILL_NAMES)
    skill = _skill_result(
        slug,
        skill_files,
        action=_skill_rollup(skill_files),
        dry_run=False,
    )
    worker = remove_worker(slug, home=home)
    files = tuple(skill.agent_files) + tuple(worker.agent_files)
    return replace(
        skill,
        ok=skill.ok and worker.ok,
        message=f"{skill.message} {worker.message}".strip(),
        agent_files=files,
        agent_action=worker.agent_action or skill.agent_action,
    )


def _cli_add(agent: Agent, project: bool, profile: str | None = None) -> list[str]:
    orch = orch_command()
    env = _env(profile)
    if agent.slug == "claude":
        argv = ["claude", "mcp", "add", "--scope", "project" if project else "user", SERVER_NAME]
        for key, value in env.items():
            argv += ["-e", f"{key}={value}"]
        return [*argv, "--", orch, "mcp", "serve"]
    if agent.slug == "codex":
        argv = ["codex", "mcp", "add", SERVER_NAME]
        for key, value in env.items():
            argv += ["--env", f"{key}={value}"]
        return [*argv, "--", orch, "mcp", "serve"]
    argv = ["agy", "mcp", "add"]
    for key, value in env.items():
        argv += ["-e", f"{key}={value}"]
    return [*argv, SERVER_NAME, orch, "mcp", "serve"]


def _cli_remove(agent: Agent, project: bool) -> list[str]:
    if agent.slug == "claude":
        return ["claude", "mcp", "remove", "--scope", "project" if project else "user", SERVER_NAME]
    return [agent.executable, "mcp", "remove", SERVER_NAME]


def _json_path(agent: Agent, *, project: Path | None, home: Path | None) -> Path:
    if project is not None:
        return project / agent.project_file
    base = _home(home)
    for name in agent.config_files:
        if (base / name).is_file():
            return base / name
    return base / agent.config_files[0]


def _json_edit(
    path: Path, agent: Agent, *, remove: bool, profile: str | None = None
) -> ConnectResult:
    data: dict[str, Any] = {}
    if path.is_file():
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            return ConnectResult(
                agent.slug,
                False,
                f"{path} has comments or is not plain JSON, so it was left untouched. "
                "Paste the snippet into it by hand.",
                snippet=server_snippet(agent, profile=profile),
            )
        if not isinstance(loaded, dict):
            return ConnectResult(agent.slug, False, f"{path} is not a JSON object; left untouched.")
        data = loaded
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        backup = path.with_name(f"{path.name}.bak-saberops-{stamp}")
        backup.write_bytes(path.read_bytes())
    key = "mcp" if agent.slug == "opencode" else "mcpServers"
    servers = data.get(key) if isinstance(data.get(key), dict) else {}
    assert isinstance(servers, dict)
    if remove:
        if SERVER_NAME not in servers:
            return ConnectResult(agent.slug, True, f"{agent.name} was not connected.")
        servers.pop(SERVER_NAME)
    else:
        servers[SERVER_NAME] = json.loads(server_snippet(agent, profile=profile))[key][SERVER_NAME]
    data[key] = servers
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)
    verb = "Disconnected" if remove else "Connected"
    return ConnectResult(agent.slug, True, f"{verb} {agent.name} ({path}).")


def _with_skill(
    result: ConnectResult,
    agent: Agent,
    *,
    home: Path | None,
    dry_run: bool,
) -> ConnectResult:
    """Attach the instruction-file step to an MCP registration result."""
    if not result.ok:
        return result
    skill = install_skill(agent.slug, home=home, dry_run=dry_run)
    return replace(
        result,
        ok=result.ok and skill.ok,
        message=f"{result.message} {skill.message}".strip(),
        skill_path=skill.skill_path,
        skill_content=skill.skill_content,
        skill_action=skill.skill_action,
        skill_files=skill.skill_files,
        agent_files=skill.agent_files,
        agent_action=skill.agent_action,
    )


def connect(
    slug: str,
    *,
    project: Path | None = None,
    dry_run: bool = False,
    runner: Runner | None = None,
    home: Path | None = None,
    skill: bool = False,
    profile: str | None = None,
) -> ConnectResult:
    """Register SaberOps with one agent (user scope, or ``project`` folder).

    With ``skill=True`` also install the small instruction file that teaches
    the submit/wait/accept loop, where the agent supports a local skill.

    ``profile`` selects the owner profile the registered server runs as; the
    entry pins the resolved store bases so a CLI that filters the child
    environment cannot fall back to the owner's default store.
    """
    from saberops import paths

    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    try:
        profile = paths.validate_profile(profile) if profile is not None else None
    except ValueError as exc:
        return ConnectResult(slug, False, str(exc))
    if project is not None and not agent.project_scope:
        return ConnectResult(slug, False, f"{agent.name} has no per-project MCP setting.")
    if agent.method == "json":
        path = _json_path(agent, project=project, home=home)
        if dry_run:
            preview = ConnectResult(
                slug,
                True,
                _with_path_warning(f"Would add SaberOps to {path}."),
                snippet=server_snippet(agent, profile=profile),
            )
            return _with_skill(preview, agent, home=home, dry_run=True) if skill else preview
        edited = _json_edit(path, agent, remove=False, profile=profile)
        json_result = ConnectResult(
            edited.agent,
            edited.ok,
            _with_path_warning(edited.message),
            edited.commands,
            edited.snippet,
        )
        return _with_skill(json_result, agent, home=home, dry_run=False) if skill else json_result
    if shutil.which(agent.executable) is None and runner is None:
        return ConnectResult(
            slug,
            False,
            f"{agent.name} is not installed.",
            snippet=server_snippet(agent, profile=profile),
        )
    run = runner or _run
    commands = []
    if not dry_run:
        # Re-adding replaces a stale entry (an old orch path or profile).
        run(_cli_remove(agent, project is not None), project)
    argv = _cli_add(agent, project is not None, profile)
    commands.append(" ".join(argv))
    if dry_run:
        would = "Would run:"
        if agent.slug == "codex":
            would += (
                f" then pin {CODEX_TOOLS_APPROVAL_KEY} = \"{CODEX_TOOLS_APPROVAL_MODE}\""
                f" in {codex_config_path(home)}"
            )
        preview = ConnectResult(
            slug, True, _with_path_warning(would), commands=tuple(commands)
        )
        return _with_skill(preview, agent, home=home, dry_run=True) if skill else preview
    result = run(argv, project)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip().splitlines()
        return ConnectResult(
            slug,
            False,
            f"{agent.name} refused: {detail[-1] if detail else 'exit ' + str(result.returncode)}",
            commands=tuple(commands),
            snippet=server_snippet(agent, profile=profile),
        )
    message = f"Connected {agent.name}."
    if agent.slug == "codex":
        pinned, note = ensure_codex_tool_approval(home)
        message = f"{message} {note}"
        if not pinned:
            return ConnectResult(
                slug,
                False,
                _with_path_warning(message),
                commands=tuple(commands),
                snippet=server_snippet(agent, profile=profile),
            )
    connected = ConnectResult(
        slug, True, _with_path_warning(message), commands=tuple(commands)
    )
    return _with_skill(connected, agent, home=home, dry_run=False) if skill else connected


def disconnect(
    slug: str,
    *,
    project: Path | None = None,
    runner: Runner | None = None,
    home: Path | None = None,
    skill: bool = True,
) -> ConnectResult:
    """Disconnect one agent; also remove the SaberOps skill it owns."""
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    if agent.method == "json":
        res = _json_edit(_json_path(agent, project=project, home=home), agent, remove=True)
    elif shutil.which(agent.executable) is None and runner is None:
        # Still remove the skill file: an uninstalled CLI may leave one behind.
        res = ConnectResult(slug, True, f"{agent.name} is not installed; nothing to disconnect.")
    else:
        argv = _cli_remove(agent, project is not None)
        result = (runner or _run)(argv, project)
        if result.returncode != 0:
            res = ConnectResult(
                slug, True, f"{agent.name} was not connected.", commands=(" ".join(argv),)
            )
        else:
            res = ConnectResult(
                slug, True, f"Disconnected {agent.name}.", commands=(" ".join(argv),)
            )
    if not skill:
        return res
    skill_result = remove_skill(slug, home=home)
    return replace(
        res,
        ok=res.ok and skill_result.ok,
        message=f"{res.message} {skill_result.message}".strip(),
        skill_path=skill_result.skill_path,
        skill_content=skill_result.skill_content,
        skill_action=skill_result.skill_action,
        skill_files=skill_result.skill_files,
    )


def is_connected(agent: Agent, *, home: Path | None = None, runner: Runner | None = None) -> bool:
    """Cheap user-scope check: read the agent's own registry, never start it."""
    base = _home(home)
    try:
        if agent.slug == "claude":
            data = json.loads((base / ".claude.json").read_text(encoding="utf-8"))
            return SERVER_NAME in (data.get("mcpServers") or {})
        if agent.slug == "codex":
            text = codex_config_path(home).read_text(encoding="utf-8")
            return re.search(rf"^\[mcp_servers\.{SERVER_NAME}\]", text, re.M) is not None
        if agent.slug == "antigravity":
            # Its registry format is private; its own list command is fast (~0.1 s).
            if runner is None and (
                shutil.which(agent.executable) is None
                or os.environ.get("PYTEST_CURRENT_TEST") is not None
            ):
                return False
            listed = (runner or _run)([agent.executable, "mcp", "list"], None)
            return (
                listed.returncode == 0
                and re.search(rf"\b{SERVER_NAME}\b", listed.stdout or "") is not None
            )
        path = _json_path(agent, project=None, home=home)
        data = json.loads(path.read_text(encoding="utf-8"))
        key = "mcp" if agent.slug == "opencode" else "mcpServers"
        return SERVER_NAME in (data.get(key) or {})
    except (OSError, ValueError, AttributeError):
        return False


def agent_rows(*, home: Path | None = None) -> list[dict[str, Any]]:
    """Every supported agent: installed, connected, and a paste-able snippet."""
    rows = []
    for agent in AGENTS:
        rows.append(
            {
                "slug": agent.slug,
                "name": agent.name,
                "installed": shutil.which(agent.executable) is not None,
                "connected": is_connected(agent, home=home),
                "snippet": server_snippet(agent),
            }
        )
    return rows
