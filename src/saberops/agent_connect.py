def orch_command() -> str:
    """Absolute path of the currently running ``orch`` launcher."""
    venv_orch = Path(sys.executable).parent / "orch"
    if venv_orch.is_file():
        return str(venv_orch.resolve())
    if sys.argv and sys.argv[0]:
        argv_path = Path(sys.argv[0])
        if argv_path.name == "orch" and argv_path.is_file():
            return str(argv_path.resolve())
    found = shutil.which("orch")
    return str(Path(found).resolve()) if found else "orch"


def conflicting_orch_on_path() -> str | None:
    """Return another ``orch`` path on PATH when it differs from the running one."""
    found = shutil.which("orch")
    if not found:
        return None
    resolved_found = str(Path(found).resolve())
    running = orch_command()
    if running != "orch" and resolved_found != running:
        return resolved_found
    return None


def _with_path_warning(message: str) -> str:
    other = conflicting_orch_on_path()
    if not other:
        return message
    return (
        f"{message} Warning: another 'orch' exists on PATH at {other}; "
        f"registering running {orch_command()}."
    )


def _env(profile: str | None = None) -> dict[str, str]:
    """The environment a registered server child needs to find the same store.

    The profile selector alone is not enough: an agent CLI may forward only the
    variables written in its own entry (Codex does), so the resolved
    state/config/cache bases are pinned as absolute paths too.  Without them a
    filtered child falls back to ``~/.local/state`` and writes to the owner's
    default store even when the connection was made for another profile.
    """
    from saberops import paths

    selected = paths.validate_profile(profile) if profile is not None else paths.active_profile()
    env: dict[str, str] = {}
    if selected:
        env["SABEROPS_PROFILE"] = selected
    env["XDG_STATE_HOME"] = str(paths.state_home())
    env["XDG_CONFIG_HOME"] = str(paths.config_home())
    env["XDG_CACHE_HOME"] = str(paths.cache_home())
    return env


def _home(home: Path | None) -> Path:
    return home if home is not None else Path.home()


def codex_home(home: Path | None = None) -> Path:
    """The Codex configuration root: ``$CODEX_HOME`` or ``~/.codex``."""
    override = os.environ.get("CODEX_HOME", "").strip()
    if override:
        return Path(override).expanduser()
    return _home(home) / ".codex"


def codex_config_path(home: Path | None = None) -> Path:
    """The Codex config file the registration command writes."""
    return codex_home(home) / "config.toml"


def _codex_header_index(lines: Sequence[str]) -> int | None:
    pattern = re.compile(
        r'^\[\s*mcp_servers\.(?:saberops|"saberops")\s*\]\s*(?:#.*)?$'
    )
    for index, line in enumerate(lines):
        if pattern.match(line):
            return index
    return None


def _codex_entry_has_approval(lines: Sequence[str], header: int) -> bool:
    key = re.compile(rf"^\s*{CODEX_TOOLS_APPROVAL_KEY}\s*=")
    for line in lines[header + 1 :]:
        if line.lstrip().startswith("["):
            return False
        if key.match(line):
            return True
    return False


def ensure_codex_tool_approval(home: Path | None = None) -> tuple[bool, str]:
    """Pin ``default_tools_approval_mode = "approve"`` on the Codex entry.

    ``codex mcp add`` cannot write this key, so it is added here after the CLI
    has written its own table.  Re-adding the server rewrites the table, which
    is why the patch runs on every connect instead of only once.  The result is
    validated with ``tomllib`` before the file is replaced; an unreadable or
    unexpected file is left untouched.
    """
    import tomllib

    path = codex_config_path(home)
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        return False, f"Could not read {path} to pin tool approval ({exc})."
    lines = text.splitlines()
    header = _codex_header_index(lines)
    if header is None:
        return False, f"Could not find {_CODEX_SERVER_HEADER} in {path}."
    if _codex_entry_has_approval(lines, header):
        return True, f"Codex tool approval already pinned in {path}."
    patch = lines[: header + 1] + [
        f'{CODEX_TOOLS_APPROVAL_KEY} = "{CODEX_TOOLS_APPROVAL_MODE}"'
    ] + lines[header + 1 :]
    updated = "\n".join(patch)
    if text.endswith("\n"):
        updated += "\n"
    try:
        tomllib.loads(updated)
    except tomllib.TOMLDecodeError as exc:
        return False, (
            f"{path} would not parse after adding tool approval ({exc}); left untouched. "
            f'Add ``{CODEX_TOOLS_APPROVAL_KEY} = "{CODEX_TOOLS_APPROVAL_MODE}"`` under '
            f"{_CODEX_SERVER_HEADER} by hand."
        )
    tmp = path.with_name(path.name + ".tmp")
    try:
        tmp.write_text(updated, encoding="utf-8")
        tmp.replace(path)
    except OSError as exc:
        return False, f"Could not write {path} to pin tool approval ({exc})."
    return True, (
        f"Pinned Codex tool approval "
        f'({CODEX_TOOLS_APPROVAL_KEY} = "{CODEX_TOOLS_APPROVAL_MODE}") in {path}.'
    )


def server_snippet(agent: Agent, *, profile: str | None = None) -> str:
    """The exact config an owner can paste by hand."""
    orch = orch_command()
    env = _env(profile)
    if agent.slug == "opencode":
        entry: dict[str, Any] = {
            "type": "local",
            "command": [orch, "mcp", "serve"],
            "enabled": True,
        }
        if env:
            entry["environment"] = env
        return json.dumps({"mcp": {SERVER_NAME: entry}}, indent=2)
    if agent.slug == "codex":
        lines = [
            f"[mcp_servers.{SERVER_NAME}]",
            f"{CODEX_TOOLS_APPROVAL_KEY} = {json.dumps(CODEX_TOOLS_APPROVAL_MODE)}",
            f'command = "{orch}"',
            'args = ["mcp", "serve"]',
        ]
        if env:
            lines += [f"[mcp_servers.{SERVER_NAME}.env]"] + [f'{k} = "{v}"' for k, v in env.items()]
        return "\n".join(lines)
    server: dict[str, Any] = {"command": orch, "args": ["mcp", "serve"]}
    if env:
        server["env"] = env
    return json.dumps({"mcpServers": {SERVER_NAME: server}}, indent=2)


def skill_path(
    agent: Agent, *, home: Path | None = None, name: str = SKILL_NAME
) -> Path | None:
    """Absolute ``SKILL.md`` path for one skill, or ``None`` when unsupported."""
    if not agent.skill_dir:
        return None
    if name not in SKILL_NAMES:
        raise ValueError(f"unknown SaberOps skill {name!r}")
    return _home(home) / agent.skill_dir / name / "SKILL.md"




def agent_file_path(agent: Agent, target: str, *, home: Path | None = None) -> Path | None:
    """Absolute definition path for one proxy, or ``None`` when unsupported."""
    if not agent.agent_dir or agent.slug not in PROXIES:
        return None
    extension = "toml" if agent.slug == "codex" else "md"
    return _home(home) / agent.agent_dir / f"{target}.{extension}"


def _proxy_body(agent: Agent, proxy: Proxy) -> str:
    """The common contract every proxy carries, without CLI-specific syntax.

    The body stays short on purpose: every launch pays for this text, so the
    full working guide is referenced as the ``saberops://guide`` resource (also
    served as the ``saberops-guide`` prompt) instead of being inlined.  The
    loop below is complete for a handoff; the resource is depth, not a
    prerequisite.
    """
    from saberops.mcp.tools import TOOL_NAMES

    missing = [name for name in PROXY_TOOLS if name not in TOOL_NAMES]
    if missing:  # a renamed tool must not leave a stale proxy behind
        raise RuntimeError(f"proxy tools are missing from the live MCP server: {missing}")
    tools = ", ".join(f"`{name}`" for name in PROXY_TOOLS)
    family = proxy.family
    return (
        f"You are {proxy.name}, a SaberOps handoff proxy. You run on {agent.name}'s\n"
        "cheapest suitable model and do nothing except hand one task to SaberOps and\n"
        "report the result.\n\n"
        "## Hard limits\n\n"
        "- Never edit files, never run shell, git or orch commands, never accept,\n"
        "  merge, push or approve billing. SaberOps owns the workspace, the gate, the\n"
        "  review and the owner's acceptance.\n"
        f"- Use the `{SERVER_NAME}` MCP server that is already connected to this\n"
        "  session. Never add or start a second SaberOps server (orch mcp serve, an\n"
        "  inline mcpServers command, or a second URL): a second process does not\n"
        "  share this session's lease, so its writes are refused or owned by the\n"
        "  wrong session.\n"
        "- One job per call. Independent pieces get one job each with its own\n"
        "  idempotency key.\n\n"
        "## The loop\n\n"
        "1. Call `preflight` with the project repo. If it reports owner-only blockers\n"
        "   (billing, sign-in, routes, check command), report them and stop.\n"
        "2. Call `submit_job` once with the repo, a one-sentence goal, testable\n"
        "   acceptance criteria, a stable idempotency key derived from the repo and\n"
        f'   goal, caller_id="proxy:{proxy.name}", and\n'
        f'   requirements={{"model_family_include": ["{family}"]}}.\n'
        "   Never send provider, model or route: SaberOps chooses the model on the\n"
        "   build route.\n"
        "3. Call `wait_job` with timeout_seconds=900 and call it again after a\n"
        "   timeout. Return early only for a blocking question or a failed dependency.\n"
        "4. Call `tail_job` only when the owner asks for live progress; pass the\n"
        "   next_sequence it returned last time.\n"
        "5. When the job finishes, call `catch_up` for the final report: the job id,\n"
        "   the final state, the route that actually ran (also in `get_job`), the\n"
        "   candidate SHA, the latest check and review, and the exact owner action.\n"
        "   Never claim the owner accepted it.\n"
        "6. Call `list_questions` only to see what is waiting for the owner.\n\n"
        "The SaberOps tools this proxy may call are: " + tools + ".\n\n"
        "Stop rule: if SaberOps reports no eligible candidate for the requested\n"
        f'family (for example the build route has no "{family}" entry), report that\n'
        "reason verbatim and stop. Never retry with another family, another provider\n"
        "or a model of your own; a request to run on one subscription must not\n"
        "silently become something else.\n\n"
        "Never claim acceptance, never push and never merge. The owner accepts from\n"
        "the SaberOps page or with the exact command catch_up returns.\n\n"
        "## More detail\n\n"
        "The full working guide is the `saberops://guide` resource (and the\n"
        "`saberops-guide` prompt) on the server already connected to this session.\n"
        "Read it once if a handoff is unusual; the loop above is enough otherwise.\n"
    )


def agent_document(slug: str, target: str) -> str:
    """Generate one proxy definition in the host CLI's own format.

    ``target`` is a proxy name from :data:`PROXIES`; a host never gets a proxy
    for its own subscription and Antigravity is never a target.
    """
    agent = agent_by_slug(slug)
    if agent is None:
        raise ValueError(f"unknown agent {slug!r}")
    proxy = next((item for item in PROXIES.get(agent.slug, ()) if item.name == target), None)
    if proxy is None:
        raise ValueError(f"{agent.name} has no proxy target {target!r}")
    description = PROXY_DESCRIPTION[proxy.name]
    model = HOST_MODEL[agent.slug]
    body = _proxy_body(agent, proxy)
    if agent.slug == "codex":
        instructions = body.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        return (
            f"{AGENT_MARKER_TOML}\n"
            f"name = {json.dumps(proxy.name)}\n"
            f"description = {json.dumps(description)}\n"
            f"model = {json.dumps(model)}\n"
            'model_reasoning_effort = "low"\n'
            "features.shell_tool = false\n"
            "features.apps = false\n"
            "features.plugins = false\n"
            "features.memories = false\n"
            f'developer_instructions = """\n{instructions}"""\n'
        )
    if agent.slug == "claude":
        tool_list = ", ".join(f"mcp__{SERVER_NAME}__{name}" for name in PROXY_TOOLS)
        return (
            "---\n"
            f"name: {proxy.name}\n"
            f"description: {description}\n"
            f"tools: {tool_list}\n"
            f"mcpServers:\n  - {SERVER_NAME}\n"
            f"model: {model}\n"
            "effort: low\n"
            "maxTurns: 40\n"
            "---\n"
            f"{AGENT_MARKER}\n\n"
            f"{body}"
        )
    if agent.slug == "opencode":
        rules = ['  - { action: "*", resource: "*", effect: deny }']
        rules += [
            f'  - {{ action: "{SERVER_NAME}_{name}", resource: "*", effect: allow }}'
            for name in PROXY_TOOLS
        ]
        return (
            "---\n"
            f"description: {description}\n"
            "mode: subagent\n"
            f"model: {model}\n"
            "permissions:\n" + "\n".join(rules) + "\n"
            "---\n"
            f"{AGENT_MARKER}\n\n"
            f"{body}"
        )
    if agent.slug == "antigravity":
        # No tools list: the agy docs warn that an unmapped tool name can hang a
        # subagent, so the contract is instruction-enforced and sandboxed.
        return (
            "---\n"
            f"name: {proxy.name}\n"
            f"description: {description}\n"
            f"model: {model}\n"
            "subagent: true\n"
            "mainAgent: false\n"
            "commandExecutionPolicy: sandbox\n"
            "---\n"
            f"{AGENT_MARKER}\n\n"
            f"{body}"
        )
    raise ValueError(f"{agent.name} has no proxy subagent format")


#: The native worker subagent `orch connect --skill` installs beside the skill
#: (F16).  It runs on the host's own vendor and cooperates through the SaberOps
#: MCP server; SaberOps verifies its evidence and never trusts its process.
WORKER_NAME = "saberops-worker"

#: Hosts that may run a native worker of their own vendor.  Antigravity is
#: excluded: it may only be the orchestrator with its own agents, never an
#: automated SaberOps worker.
WORKER_VENDOR: dict[str, str] = {
    "claude": "claude",
    "codex": "codex",
    "opencode": "opencode",
}

#: Tools the native worker calls.  Every name is checked against the live
#: server before a definition is generated.
WORKER_TOOLS: tuple[str, ...] = (
    "get_job",
    "native_claim",
    "native_heartbeat",
    "native_controls",
    "record_native_attempt",
)

WORKER_DESCRIPTION = (
    "Do one SaberOps job natively on this CLI's own subscription. Use only when "
    "SaberOps hands you a claimed job; SaberOps prepares the worktree and verifies "
    "the result."
)


def worker_file_path(agent: Agent, *, home: Path | None = None) -> Path | None:
    """Absolute definition path for the native worker, or ``None`` if unsupported."""
    if not agent.agent_dir or agent.slug not in WORKER_VENDOR:
        return None
    extension = "toml" if agent.slug == "codex" else "md"
    return _home(home) / agent.agent_dir / f"{WORKER_NAME}.{extension}"


def _worker_body(agent: Agent) -> str:
    from saberops.mcp.tools import TOOL_NAMES
    from saberops.native_workers import NATIVE_TOOL_NAMES
    from saberops.validation_policy import WORKER_INSTRUCTIONS

    known = set(TOOL_NAMES) | set(NATIVE_TOOL_NAMES)
    missing = [name for name in WORKER_TOOLS if name not in known]
    if missing:  # a renamed tool must not leave a stale definition behind
        raise RuntimeError(f"native worker tools are missing from the live server: {missing}")
    vendor = WORKER_VENDOR[agent.slug]
    tools = ", ".join(f"`{name}`" for name in WORKER_TOOLS)
    return (
        f"You are {WORKER_NAME}, a SaberOps native worker running on {agent.name}'s own\n"
        "subscription. SaberOps owns the job record, the worktree, the gate, the review\n"
        "and the owner's acceptance; you only do the work and report evidence.\n\n"
        "## Hard limits\n\n"
        "- Work only inside the `worktree` that `native_claim` returns, and commit\n"
        "  only on the `branch` it returns. Never edit, commit on, or run git in the\n"
        "  canonical checkout; SaberOps fails the attempt closed if it moves.\n"
        "  Your edits and shell are confined to that worktree by this CLI's own\n"
        "  sandbox and permission rules; respect them and never try to escape them.\n"
        "- Never accept, merge, push, approve billing, or start a second SaberOps\n"
        "  server. Never claim the owner accepted anything.\n"
        "- One job per claim. Never claim a second job while this one is unfinished.\n\n"
        "## The loop\n\n"
        "1. `native_claim` with the job id SaberOps gave you, your vendor\n"
        f'   ("{vendor}") and your model name. It returns run_id, worktree, branch,\n'
        "   base_sha and the heartbeat deadline. If it is refused, report the reason\n"
        "   verbatim and stop.\n"
        "2. Work in the worktree. Commit on the branch. Keep the canonical checkout\n"
        "   untouched.\n"
        "3. Call `native_heartbeat` at least every few minutes with a short\n"
        "   `progress` line. It returns any owner `steering_notes` (apply them to the\n"
        "   current work) and `stop_requested`. If `stop_requested` is true, stop\n"
        "   immediately and report that you stopped; never continue the task.\n"
        "4. When the work is committed, call `record_native_attempt` with vendor,\n"
        "   model, base_sha, candidate_sha, worktree, a short transcript and the\n"
        "   times. SaberOps verifies lineage and isolation, runs the project gate and\n"
        "   an independent different-family review. If it refuses, report the exact\n"
        "   error and stop; do not retry with different evidence.\n"
        "5. Return the run id, the final state and the exact owner action SaberOps\n"
        "   reported. Only the owner accepts.\n\n"
        + WORKER_INSTRUCTIONS
        + "\n\n"
        "The tools this worker calls are: " + tools + ".\n"
        "They exist only while the owner has enabled native workers\n"
        "(`ORCH_NATIVE_WORKERS=1`). If they are missing, report that SaberOps native\n"
        "workers are off and do not fall back to editing files by yourself.\n"
    )


def worker_document(slug: str) -> str:
    """Generate the ``saberops-worker`` definition in the host CLI's format."""
    agent = agent_by_slug(slug)
    if agent is None:
        raise ValueError(f"unknown agent {slug!r}")
    if agent.slug not in WORKER_VENDOR:
        raise ValueError(f"{agent.name} may not run an automated native worker")
    body = _worker_body(agent)
    if agent.slug == "codex":
        instructions = body.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        return (
            f"{AGENT_MARKER_TOML}\n"
            f"name = {json.dumps(WORKER_NAME)}\n"
            f"description = {json.dumps(WORKER_DESCRIPTION)}\n"
            'sandbox_mode = "workspace-write"\n'
            "features.apps = false\n"
            "features.plugins = false\n"
            "features.memories = false\n"
            f'developer_instructions = """\n{instructions}"""\n'
        )
    if agent.slug == "claude":
        builtin = ("Read", "Edit", "Write", "Bash", "Glob", "Grep")
        tool_list = ", ".join(
            [*builtin, *(f"mcp__{SERVER_NAME}__{name}" for name in WORKER_TOOLS)]
        )
        return (
            "---\n"
            f"name: {WORKER_NAME}\n"
            f"description: {WORKER_DESCRIPTION}\n"
            f"tools: {tool_list}\n"
            f"mcpServers:\n  - {SERVER_NAME}\n"
            "model: inherit\n"
            "permissionMode: acceptEdits\n"
            "---\n"
            f"{AGENT_MARKER}\n\n"
            f"{body}"
        )
    if agent.slug == "opencode":
        rules = ['  - { action: "*", resource: "*", effect: deny }']
        rules += [
            f'  - {{ action: "{action}", resource: "*", effect: allow }}'
            for action in ("read", "edit", "bash")
        ]
        rules += [
            f'  - {{ action: "{SERVER_NAME}_{name}", resource: "*", effect: allow }}'
            for name in WORKER_TOOLS
        ]
        return (
            "---\n"
            f"description: {WORKER_DESCRIPTION}\n"
            "mode: subagent\n"
            "permissions:\n" + "\n".join(rules) + "\n"
            "---\n"
            f"{AGENT_MARKER}\n\n"
            f"{body}"
        )
    raise ValueError(f"{agent.name} has no native worker subagent format")


def _write_worker_file(
    agent: Agent, path: Path, content: str, *, dry_run: bool
) -> AgentFile:
    if dry_run:
        return AgentFile(
            WORKER_NAME,
            str(path),
            content=content,
            action="would-install",
            message=f"Would write the SaberOps native worker to {path}.",
        )
    if path.exists():
        if not path.is_file():
            return AgentFile(
                WORKER_NAME,
                str(path),
                action="refused",
                message=f"{path} is not a regular file; left untouched.",
                ok=False,
            )
        existing = path.read_text(encoding="utf-8", errors="replace")
        if AGENT_MARKER not in existing and AGENT_MARKER_TOML not in existing:
            return AgentFile(
                WORKER_NAME,
                str(path),
                action="refused",
                message=f"{path} exists and was not written by SaberOps; left untouched.",
                ok=False,
            )
        if existing == content:
            return AgentFile(
                WORKER_NAME,
                str(path),
                action="unchanged",
                message=f"SaberOps native worker already up to date at {path}.",
            )
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(content, encoding="utf-8")
        tmp.replace(path)
    except OSError as exc:
        return AgentFile(
            WORKER_NAME,
            str(path),
            action="refused",
            message=f"Could not write {path}: {exc}",
            ok=False,
        )
    return AgentFile(
        WORKER_NAME,
        str(path),
        action="installed",
        message=f"Installed the SaberOps native worker at {path}.",
    )


def install_worker(slug: str, *, home: Path | None = None, dry_run: bool = False) -> ConnectResult:
    """Install the native worker definition this host CLI supports (F16)."""
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    path = worker_file_path(agent, home=home)
    if path is None:
        return ConnectResult(
            slug,
            True,
            f"{agent.name} may not run an automated SaberOps worker; "
            "Antigravity stays an orchestrator only.",
            agent_action="unsupported",
        )
    content = worker_document(agent.slug)
    file = _write_worker_file(agent, path, content, dry_run=dry_run)
    return ConnectResult(
        slug,
        file.ok,
        file.message,
        agent_files=(file,),
        agent_action=file.action,
    )


