def install_skill(
    slug: str, *, home: Path | None = None, dry_run: bool = False
) -> ConnectResult:
    """Install the SaberOps skill plus the native worker definition (F16).

    Both files carry an ownership marker, so a file SaberOps did not write is
    never overwritten or later removed.
    """
    skill = _install_skill_file(slug, home=home, dry_run=dry_run)
    worker = install_worker(slug, home=home, dry_run=dry_run)
    files = tuple(skill.agent_files) + tuple(worker.agent_files)
    return replace(
        skill,
        ok=skill.ok and worker.ok,
        message=f"{skill.message} {worker.message}".strip(),
        agent_files=files,
        agent_action=worker.agent_action or skill.agent_action,
    )


def remove_skill(slug: str, *, home: Path | None = None) -> ConnectResult:
    """Remove the SaberOps skill and the native worker definition it owns."""
    skill = _remove_skill_file(slug, home=home)
    worker = remove_worker(slug, home=home)
    files = tuple(skill.agent_files) + tuple(worker.agent_files)
    return replace(
        skill,
        ok=skill.ok and worker.ok,
        message=f"{skill.message} {worker.message}".strip(),
        agent_files=files,
        agent_action=worker.agent_action or skill.agent_action,
    )


def _cli_add(agent: Agent, project: bool) -> list[str]:
    orch = orch_command()
    env = _env()
    if agent.slug == "claude":
        argv = ["claude", "mcp", "add", "--scope", "project" if project else "user", SERVER_NAME]
        for key, value in env.items():
            argv += ["-e", f"{key}={value}"]
        return [*argv, "--", orch, "mcp", "serve"]
    if agent.slug == "codex":
        argv = ["codex", "mcp", "add", SERVER_NAME]
        for key, value in env.items():
            argv += ["--env", f"{key}={value}"]
        return [*argv, "--", orch, "mcp", "serve"]
    argv = ["agy", "mcp", "add"]
    for key, value in env.items():
        argv += ["-e", f"{key}={value}"]
    return [*argv, SERVER_NAME, orch, "mcp", "serve"]


def _cli_remove(agent: Agent, project: bool) -> list[str]:
    if agent.slug == "claude":
        return ["claude", "mcp", "remove", "--scope", "project" if project else "user", SERVER_NAME]
    return [agent.executable, "mcp", "remove", SERVER_NAME]


def _json_path(agent: Agent, *, project: Path | None, home: Path | None) -> Path:
    if project is not None:
        return project / agent.project_file
    base = _home(home)
    for name in agent.config_files:
        if (base / name).is_file():
            return base / name
    return base / agent.config_files[0]


def _json_edit(path: Path, agent: Agent, *, remove: bool) -> ConnectResult:
    data: dict[str, Any] = {}
    if path.is_file():
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            return ConnectResult(
                agent.slug,
                False,
                f"{path} has comments or is not plain JSON, so it was left untouched. "
                "Paste the snippet into it by hand.",
                snippet=server_snippet(agent),
            )
        if not isinstance(loaded, dict):
            return ConnectResult(agent.slug, False, f"{path} is not a JSON object; left untouched.")
        data = loaded
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        backup = path.with_name(f"{path.name}.bak-saberops-{stamp}")
        backup.write_bytes(path.read_bytes())
    key = "mcp" if agent.slug == "opencode" else "mcpServers"
    servers = data.get(key) if isinstance(data.get(key), dict) else {}
    assert isinstance(servers, dict)
    if remove:
        if SERVER_NAME not in servers:
            return ConnectResult(agent.slug, True, f"{agent.name} was not connected.")
        servers.pop(SERVER_NAME)
    else:
        servers[SERVER_NAME] = json.loads(server_snippet(agent))[key][SERVER_NAME]
    data[key] = servers
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)
    verb = "Disconnected" if remove else "Connected"
    return ConnectResult(agent.slug, True, f"{verb} {agent.name} ({path}).")


def _with_skill(
    result: ConnectResult,
    agent: Agent,
    *,
    home: Path | None,
    dry_run: bool,
) -> ConnectResult:
    """Attach the instruction-file step to an MCP registration result."""
    if not result.ok:
        return result
    skill = install_skill(agent.slug, home=home, dry_run=dry_run)
    return replace(
        result,
        ok=result.ok and skill.ok,
        message=f"{result.message} {skill.message}".strip(),
        skill_path=skill.skill_path,
        skill_content=skill.skill_content,
        skill_action=skill.skill_action,
        agent_files=skill.agent_files,
        agent_action=skill.agent_action,
    )


def connect(
    slug: str,
    *,
    project: Path | None = None,
    dry_run: bool = False,
    runner: Runner | None = None,
    home: Path | None = None,
    skill: bool = False,
) -> ConnectResult:
    """Register SaberOps with one agent (user scope, or ``project`` folder).

    With ``skill=True`` also install the small instruction file that teaches
    the submit/wait/accept loop, where the agent supports a local skill.
    """
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    if project is not None and not agent.project_scope:
        return ConnectResult(slug, False, f"{agent.name} has no per-project MCP setting.")
    if agent.method == "json":
        path = _json_path(agent, project=project, home=home)
        if dry_run:
            preview = ConnectResult(
                slug,
                True,
                _with_path_warning(f"Would add SaberOps to {path}."),
                snippet=server_snippet(agent),
            )
            return _with_skill(preview, agent, home=home, dry_run=True) if skill else preview
        edited = _json_edit(path, agent, remove=False)
        json_result = ConnectResult(
            edited.agent,
            edited.ok,
            _with_path_warning(edited.message),
            edited.commands,
            edited.snippet,
        )
        return _with_skill(json_result, agent, home=home, dry_run=False) if skill else json_result
    if shutil.which(agent.executable) is None and runner is None:
        return ConnectResult(
            slug, False, f"{agent.name} is not installed.", snippet=server_snippet(agent)
        )
    run = runner or _run
    commands = []
    if not dry_run:
        # Re-adding replaces a stale entry (an old orch path or profile).
        run(_cli_remove(agent, project is not None), project)
    argv = _cli_add(agent, project is not None)
    commands.append(" ".join(argv))
    if dry_run:
        preview = ConnectResult(
            slug, True, _with_path_warning("Would run:"), commands=tuple(commands)
        )
        return _with_skill(preview, agent, home=home, dry_run=True) if skill else preview
    result = run(argv, project)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip().splitlines()
        return ConnectResult(
            slug,
            False,
            f"{agent.name} refused: {detail[-1] if detail else 'exit ' + str(result.returncode)}",
            commands=tuple(commands),
            snippet=server_snippet(agent),
        )
    connected = ConnectResult(
        slug, True, _with_path_warning(f"Connected {agent.name}."), commands=tuple(commands)
    )
    return _with_skill(connected, agent, home=home, dry_run=False) if skill else connected


def disconnect(
    slug: str,
    *,
    project: Path | None = None,
    runner: Runner | None = None,
    home: Path | None = None,
    skill: bool = True,
) -> ConnectResult:
    """Disconnect one agent; also remove the SaberOps skill it owns."""
    agent = agent_by_slug(slug)
    if agent is None:
        return ConnectResult(slug, False, f"Unknown agent {slug!r}.")
    if agent.method == "json":
        res = _json_edit(_json_path(agent, project=project, home=home), agent, remove=True)
    elif shutil.which(agent.executable) is None and runner is None:
        # Still remove the skill file: an uninstalled CLI may leave one behind.
        res = ConnectResult(slug, True, f"{agent.name} is not installed; nothing to disconnect.")
    else:
        argv = _cli_remove(agent, project is not None)
        result = (runner or _run)(argv, project)
        if result.returncode != 0:
            res = ConnectResult(
                slug, True, f"{agent.name} was not connected.", commands=(" ".join(argv),)
            )
        else:
            res = ConnectResult(
                slug, True, f"Disconnected {agent.name}.", commands=(" ".join(argv),)
            )
    if not skill:
        return res
    skill_result = remove_skill(slug, home=home)
    return replace(
        res,
        ok=res.ok and skill_result.ok,
        message=f"{res.message} {skill_result.message}".strip(),
        skill_path=skill_result.skill_path,
        skill_action=skill_result.skill_action,
    )


def is_connected(agent: Agent, *, home: Path | None = None, runner: Runner | None = None) -> bool:
    """Cheap user-scope check: read the agent's own registry, never start it."""
    base = _home(home)
    try:
        if agent.slug == "claude":
            data = json.loads((base / ".claude.json").read_text(encoding="utf-8"))
            return SERVER_NAME in (data.get("mcpServers") or {})
        if agent.slug == "codex":
            text = (base / ".codex" / "config.toml").read_text(encoding="utf-8")
            return re.search(rf"^\[mcp_servers\.{SERVER_NAME}\]", text, re.M) is not None
        if agent.slug == "antigravity":
            # Its registry format is private; its own list command is fast (~0.1 s).
            if runner is None and (
                shutil.which(agent.executable) is None
                or os.environ.get("PYTEST_CURRENT_TEST") is not None
            ):
                return False
            listed = (runner or _run)([agent.executable, "mcp", "list"], None)
            return (
                listed.returncode == 0
                and re.search(rf"\b{SERVER_NAME}\b", listed.stdout or "") is not None
            )
        path = _json_path(agent, project=None, home=home)
        data = json.loads(path.read_text(encoding="utf-8"))
        key = "mcp" if agent.slug == "opencode" else "mcpServers"
        return SERVER_NAME in (data.get(key) or {})
    except (OSError, ValueError, AttributeError):
        return False


def agent_rows(*, home: Path | None = None) -> list[dict[str, Any]]:
    """Every supported agent: installed, connected, and a paste-able snippet."""
    rows = []
    for agent in AGENTS:
        rows.append(
            {
                "slug": agent.slug,
                "name": agent.name,
                "installed": shutil.which(agent.executable) is not None,
                "connected": is_connected(agent, home=home),
                "snippet": server_snippet(agent),
            }
        )
    return rows
